def norm785(mem,q,candidate):
    if not candidate: return float('-inf')
    # Score a candidate GENERATED by a frozen model; never an offline gold answer.
    dummy={'B0':(0,0),'B1':(0,0)}
    lp,_,_,_,calls=score_candidate(mem,q,candidate,dummy,selected_layers=(4,20,40,79))
    assert calls>=4, 'ATTENTION_INSTRUMENTATION_INACTIVE'
    n=len(tok(candidate,add_special_tokens=False).input_ids)
    return float(lp)/max(n,1)
def choose785(preds,scores):
    # Model-only inputs. Neither gold nor CURRENT/HISTORICAL view enters here.
    # Cross-compare two generated candidate strings under BOTH isolated caches.
    a,b=preds['B0'],preds['B1']
    if not a or not b: return {'action':'ABSTAIN','reason':'EMPTY_GENERATION'}
    if a==b:
        return {'action':'KEEP_PAIR','reason':'AGREEMENT','answer':a}
    # Preference for a source is based on how strongly its cache supports its own
    # answer relative to the alternative cache, AND prefers it to rival answer.
    utility={}
    for source,other in [('B0','B1'),('B1','B0')]:
        own=preds[source];rival=preds[other]
        own_self=scores[source][own];own_other=scores[other][own]
        rival_self=scores[source][rival]
        utility[source]={'support_gap':own_self-own_other,
                         'candidate_gap':own_self-rival_self}
    valid=[s for s,v in utility.items() if v['support_gap']>=MIN_SUPPORT_GAP
           and v['candidate_gap']>=MIN_CANDIDATE_GAP]
    if len(valid)!=1:
        return {'action':'ABSTAIN','reason':'NO_UNIQUE_EVIDENCE','utility':utility}
    s=valid[0]
    return {'action':'SWITCH_'+s,'reason':'UNIQUE_CROSS_SCORE','answer':preds[s],
            'utility':utility}

